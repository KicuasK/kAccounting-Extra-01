import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import test from 'node:test'

const directory = new URL('../src/', import.meta.url)
const main = readFileSync(new URL('main.ts', directory), 'utf8')
const client = readFileSync(new URL('session-client.ts', directory), 'utf8')
const source = readdirSync(directory, { recursive: true }).filter(name => name.endsWith('.ts'))
  .map(name => readFileSync(new URL(name, directory), 'utf8')).join('\n')
const css = readFileSync(new URL('style.css', directory), 'utf8')
const index = readFileSync(new URL('../index.html', import.meta.url), 'utf8')
function between(start: string, end: string): string {
  const first = main.indexOf(start), last = main.indexOf(end, first + start.length)
  assert.ok(first >= 0 && last > first)
  return main.slice(first, last)
}
test('runtime API content never enters an HTML parsing sink', () => {
  assert.equal(source.match(/\.innerHTML\s*=/g)?.length, 1)
  assert.doesNotMatch(between('app.innerHTML = `', '`\n\nconst shell'), /\$\{/)
  assert.doesNotMatch(source, /\.outerHTML\s*=|insertAdjacentHTML\s*\(|document\.write\s*\(|createContextualFragment\s*\(|new\s+DOMParser\b/)
  assert.match(between('function createAccountName', 'function createStateCell'), /span\.textContent = segment\.text/)
  assert.match(main, /books\.forEach\(id => bookSelect\.append\(new Option\(id, id\)\)\)/)
})
test('one JSON transport enforces origin, cache, content type and redirect controls', () => {
  assert.equal(source.match(/\bfetch\s*\(/g)?.length, 1)
  assert.match(client, /credentials: 'same-origin'/)
  assert.match(client, /cache: 'no-store'/)
  assert.match(client, /redirect: 'error'/)
  assert.match(client, /includes\('application\/json'\)/)
  assert.doesNotMatch(source, /\b(?:XMLHttpRequest|WebSocket|EventSource)\b|sendBeacon\s*\(/)
})
test('financial workspaces share pinned requests; selection stays explicit and data is not persisted in the browser', () => {
  assert.match(main, /mountAccountMaintenance\(maintenanceHost, context\)/)
  assert.match(main, /mountJournalUI\(workspacePage, context\)/)
  assert.match(main, /mountReportsUI\(workspacePage, context, activeView\)/)
  assert.match(main, /const request = pinnedWorkspaceRequest\(selection, current, requestJson/)
  assert.match(main, /mountStorageUI\(workspacePage, context\)/)
  assert.match(main, /openBook\.addEventListener\('click'/)
  assert.match(main, /closeBook\.addEventListener\('click'/)
  assert.match(main, /if \(!selectedBookId \|\| sessionBusy\) return/)
  assert.doesNotMatch(source, /localStorage|sessionStorage|indexedDB|document\.cookie/)
  assert.match(index, /<title>kAccounting-Extra-01<\/title>/)
})
test('book transitions clear old data and reconcile server state even after a failed write', () => {
  const clear = between('function clearBookView', 'function updateSessionControls')
  assert.match(clear, /accountRequests\.cancel\(\)/)
  assert.match(clear, /accountTree = \[\]; balances\.clear\(\)/)
  assert.match(clear, /renderSummary\(\[\]\)/)
  const session = between('async function syncSession', "bookSelect.addEventListener")
  assert.match(session, /clearBookView\(\)/)
  assert.match(session, /catch \(error\) \{ transitionFailure = error \}/)
  assert.match(session, /parseSession\(await requestJson\('\/api\/session'/)
})
test('parsed exact balances and account trees pass the request gate before rendering', () => {
  const loader = between('async function loadAccounts', "refreshButton.addEventListener")
  const parse = loader.indexOf('const nextAccountTree = parseAccountTree(responseBody)')
  const publish = loader.indexOf('accountTree = nextAccountTree')
  assert.ok(parse >= 0 && publish > parse)
  assert.match(loader.slice(parse, publish), /if \(!accountRequests\.isCurrent\(controller\)\) return/)
  assert.match(loader, /accountBalances\(/)
  assert.match(loader, /session.bookId !== bookId/)
  assert.match(loader, /if \(accountRequests.finish\(controller\)\)/)
  assert.match(loader, /error.name === 'AbortError'/)
})
